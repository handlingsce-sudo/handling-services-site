/* =====================================================
   CHANGE LANGUAGE
===================================================== */

function changeLanguage(language) {

    if (!translations[language]) {
        return;
    }

    /*
       Update all elements having data-i18n
    */

    document.querySelectorAll("[data-i18n]").forEach(element => {

        const key = element.getAttribute("data-i18n");

        if (translations[language][key]) {

            element.innerHTML = translations[language][key];

        }

    });


    /*
       Update HTML language
    */

    document.documentElement.lang = language;


    /*
       Update language button
    */

    const currentLanguage =
        document.getElementById("currentLanguage");

    if (currentLanguage) {

        currentLanguage.textContent =
            language.toUpperCase();

    }


    /*
       Save selected language
    */

    localStorage.setItem(
        "handlingLanguage",
        language
    );


    /*
       Update document title
    */

    if (language === "fr") {

        document.title =
            "Handling Services SARL | Manutention, Déchargement & Location de Matériel à Agadir et Dakhla";

    } else {

        document.title =
            "Handling Services SARL | Handling, Unloading & Equipment Rental in Agadir and Dakhla";

    }


    /*
       Update SEO description
    */

    const description =
        document.querySelector('meta[name="description"]');

    if (description) {

        if (language === "fr") {

            description.setAttribute(
                "content",
                "Handling Services SARL intervient depuis 1997 dans la manutention, le déchargement et la location de matériel à Agadir et Dakhla."
            );

        } else {

            description.setAttribute(
                "content",
                "Handling Services SARL has been providing handling, unloading and equipment rental services in Agadir and Dakhla since 1997."
            );

        }

    }


    /*
       Close language menu on mobile / click
    */

    document.body.classList.remove("language-open");
}


/* =====================================================
   LOAD SAVED LANGUAGE
===================================================== */

document.addEventListener("DOMContentLoaded", () => {

    const savedLanguage =
        localStorage.getItem("handlingLanguage");

    /*
       French by default
    */

    if (savedLanguage === "en") {

        changeLanguage("en");

    } else {

        changeLanguage("fr");

    }


    /*
       Language button
    */

    const languageButton =
        document.getElementById("languageButton");

    const languageMenu =
        document.querySelector(".language-menu");


    if (languageButton && languageMenu) {

        languageButton.addEventListener("click", (event) => {

            event.stopPropagation();

            languageMenu.classList.toggle("open");

        });

    }


    /*
       Close menu when clicking elsewhere
    */

    document.addEventListener("click", () => {

        if (languageMenu) {

            languageMenu.classList.remove("open");

        }

    });

});


